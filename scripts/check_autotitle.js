// Unit check for out/autoTitle.js: default rules, merge, cleaning, title, skip rules, stage planning. Never calls claude.
const path = require('path');
const OUT = process.env.CCS_OUT || path.join(__dirname, '..', 'out');
const a = require(path.join(OUT, 'autoTitle.js'));
const fails = [];
const check = (w, c) => { if (!c) { fails.push(w); } };
check('defaults', a.DEFAULT_RULES.length >= 26 && a.DEFAULT_RULES.every((r) => r.emoji && r.keywords.length));
const rules = a.mergeRules([], false);
check('emoji billing', a.pickEmoji('Fix the checkout and payment flow', rules) === '💳');
check('emoji bug', a.pickEmoji('app crashes with an error on start', rules) === '🐛');
check('emoji default', a.pickEmoji('hello there friend of mine', []) === '💬' && a.pickEmoji('zzz qqq', rules) === '💬');
check('word boundary', a.pickEmoji('the catalog and category', rules) === '💬');
const user = a.parseRules([{ emoji: '🎯', keywords: ['Rocket', ' '] }, { emoji: 'x', keywords: ['a'] }, { emoji: '🎯', keywords: [] }, 5, { emoji: '🐱', keywords: 'cat' }]);
check('parse rules', user.length === 1 && user[0].keywords.join() === 'rocket');
const m = a.mergeRules(user, false);
check('merge adds first', m[0].emoji === '🎯' && m.length === a.DEFAULT_RULES.length + 1);
const ov = a.mergeRules([{ emoji: '🐾', keywords: ['zebra'] }], false);
check('merge overrides same emoji', ov.filter((r) => r.emoji === '🐾').length === 1 && a.pickEmoji('a zebra', ov) === '🐾' && a.pickEmoji('my dog', ov) === '💬');
check('replace', a.mergeRules(user, true).length === 1 && a.pickEmoji('crash error', a.mergeRules(user, true)) === '💬');
check('clean', a.cleanPrompt('<b>Hello</b> `code` deadbeefdeadbeef **bold**') === 'Hello code bold');
check('title sentence', a.makeTitle('please fix the login screen. Then also do other things') === 'Please fix the login screen');
check('title profanity', !/damn/i.test(a.makeTitle('why is this damn build so slow today')));
const long = a.makeTitle('alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima mike');
check('title 50', long.length <= 50 && long.startsWith('Alpha') && !long.endsWith(' ') && long.endsWith('hotel'));
check('skip', a.isSkippable('/clear') && a.isSkippable('fix it now') && a.isSkippable('<task-notification> a b c d e f') && a.isSkippable('read the tool-use-id please now ok') && !a.isSkippable('fix the login screen layout please'));
check('custom title', a.customTitleOf('x\n{"type":"custom-title","customTitle":"A"}\n{"type":"custom-title","customTitle":"B"}\n{"type":"custom-ti') === 'B' && a.customTitleOf('{}') === undefined);
const P = ['fix the login screen layout please', 'ok', 'now the database migration'];
check('build', a.buildTitle(P, rules) === '🎨 Fix the login screen layout please' || a.buildTitle(P, rules).endsWith('Fix the login screen layout please'));
check('build none', a.buildTitle(['/x', 'hi'], rules) === undefined);
const p1 = a.planTitle({ prompts: [P[0]] }, undefined);
check('stage1', !p1.skip && !p1.final);
check('wait', a.planTitle({ prompts: [P[0], 'ok'] }, { n: 1, t: 'T' }).skip === true && !a.planTitle({ prompts: [P[0], 'ok'] }, { n: 1, t: 'T' }).final);
const p3 = a.planTitle({ prompts: P }, { n: 1, t: 'T' });
check('stage2', !p3.skip && p3.final);
check('already done', a.planTitle({ prompts: P }, { n: 3, t: 'T' }).skip === true);
check('user titled', a.planTitle({ prompts: P, custom: 'Mine' }, undefined).final === true && a.planTitle({ prompts: P, custom: 'Mine' }, { n: 1, t: 'T' }).skip === true);
check('own title not user', !a.planTitle({ prompts: P, custom: 'T' }, { n: 1, t: 'T' }).skip);
check('no usable prompt', a.planTitle({ prompts: ['/clear'] }, undefined).skip === true);
if (fails.length) { console.error('AutoTitle check FAILED:\n - ' + fails.join('\n - ')); process.exit(1); }
console.log('AutoTitle check passed.');
